def verify_normalized_coordinate_refinement_dependency() -> None:
    print("\n=== Dependency check: finite use of normalized coordinate refinement ===")

    for s in range(2, 7):
        for n in range(1, 7):
            grid = {normalized_delta_rho(sequence, s) for sequence in product(range(1, s + 1), repeat=n)}
            expected_grid = {Fraction(D, s**n) for D in range(0, s**n)}
            assert grid == expected_grid
            assert min(grid) == 0
            assert max(grid) == Fraction(s**n - 1, s**n)

            sorted_grid = sorted(grid)
            if len(sorted_grid) > 1:
                spacings = {sorted_grid[i + 1] - sorted_grid[i] for i in range(len(sorted_grid) - 1)}
                assert spacings == {Fraction(1, s**n)}

            for sequence in product(range(1, s + 1), repeat=n):
                for sigma_next in range(1, s + 1):
                    rho_n = normalized_delta_rho(sequence, s)
                    rho_np1 = normalized_delta_rho(sequence + (sigma_next,), s)
                    expected = rho_n + Fraction(sigma_next - 1, s ** (n + 1))
                    assert rho_np1 == expected

    print("[OK] The finite coordinate spectrum used by macro-classes is exactly {D/s^n}")
    print("[OK] Recursive refinement appends one internal state at scale s^{-(n+1)}")


