@dataclass(frozen=True)
class EventuallyPeriodicFamily:
    """Infinite recursively compatible state family with fixed ancestor."""

    a: int
    finite_prefix: StateSequence
    period: StateSequence
    s: int

    def __post_init__(self) -> None:
        assert self.a >= 1
        assert self.s >= 2
        assert len(self.period) >= 1
        for sigma in self.finite_prefix + self.period:
            assert 1 <= sigma <= self.s

    def state_at(self, index_one_based: int) -> int:
        assert index_one_based >= 1
        L = len(self.finite_prefix)
        if index_one_based <= L:
            return self.finite_prefix[index_one_based - 1]
        return self.period[(index_one_based - L - 1) % len(self.period)]

    def prefix(self, n: int) -> StateSequence:
        assert n >= 1
        return tuple(self.state_at(i) for i in range(1, n + 1))

    def spin_limit(self) -> Fraction:
        return sum((eta(sigma, self.s) for sigma in self.period), Fraction(0)) / len(self.period)

    def rho_limit(self) -> Fraction:
        """Exact value of the infinite base-s expansion of Delta rho."""
        L = len(self.finite_prefix)
        p = len(self.period)

        finite_part = sum(
            Fraction(self.finite_prefix[j - 1] - 1, self.s**j)
            for j in range(1, L + 1)
        )
        period_block = sum(
            Fraction(self.period[t - 1], 1) / (self.s**t) - Fraction(1, self.s**t)
            for t in range(1, p + 1)
        )
        periodic_tail = Fraction(1, self.s**L) * period_block / (1 - Fraction(1, self.s**p))
        value = finite_part + periodic_tail
        assert Fraction(0) <= value <= Fraction(1)
        return value


@dataclass(frozen=True)
class AsymptoticMacroProfile:
    """Exact macro-equivalence quotient data.

    The r_O1_class field is an abstract class modulo bounded difference, not a
    leading slope.  Equal labels mean that the two logarithmic-coordinate
    profiles are known to differ by O(1).  Unequal labels mean that the script
    does not allow macro-equivalence through the r-clause.
    """

    rho_limit: Fraction
    r_O1_class: str
    spin_limit: Fraction



def profile_from_family(
    fam: EventuallyPeriodicFamily,
    *,
    r_O1_class: str = "generated-O1-class",
) -> AsymptoticMacroProfile:
    return AsymptoticMacroProfile(
        rho_limit=fam.rho_limit(),
        r_O1_class=r_O1_class,
        spin_limit=fam.spin_limit(),
    )


def macro_equivalent_profiles(p: AsymptoticMacroProfile, q: AsymptoticMacroProfile) -> bool:
    return (
        p.rho_limit == q.rho_limit
        and p.r_O1_class == q.r_O1_class
        and p.spin_limit == q.spin_limit
    )


