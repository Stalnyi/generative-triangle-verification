StateSequence = tuple[int, ...]


# ---------------------------------------------------------------------------
# Model dependencies already verified in earlier sections
# ---------------------------------------------------------------------------

def c_A(m: int, k: int, s: int) -> int:
    assert m >= 1
    assert k >= 2
    assert s >= 2
    return (s - 1) * m + 1 - k


def F(x: int, sigma: int, *, m: int, k: int, s: int) -> int:
    assert x >= 1
    assert 1 <= sigma <= s
    return s * x + sigma - c_A(m, k, s)


def level_start(n: int, *, m: int, k: int, s: int) -> int:
    assert n >= 0
    numerator = k * (s**n - 1)
    assert numerator % (s - 1) == 0
    return m + numerator // (s - 1)


def generate_x(a: int, sequence: Sequence[int], *, m: int, k: int, s: int) -> int:
    assert m <= a <= m + k - 1
    x = a
    for sigma in sequence:
        x = F(x, sigma, m=m, k=k, s=s)
    return x


def digit_coordinate(sequence: Sequence[int], s: int) -> int:
    n = len(sequence)
    D = 0
    for j, sigma in enumerate(sequence, start=1):
        assert 1 <= sigma <= s
        D += (sigma - 1) * s ** (n - j)
    return D


def u_from_sequence(a: int, sequence: Sequence[int], *, m: int, k: int, s: int) -> int:
    n = len(sequence)
    return (a - m) * s**n + digit_coordinate(sequence, s)


def normalized_delta_rho(sequence: Sequence[int], s: int) -> Fraction:
    n = len(sequence)
    assert n >= 1
    return Fraction(digit_coordinate(sequence, s), s**n)


def exact_r_exponent(a: int, sequence: Sequence[int], *, m: int, k: int, s: int) -> int:
    u = u_from_sequence(a, sequence, m=m, k=k, s=s)
    assert u >= 0
    return u + 1


def numeric_r(a: int, sequence: Sequence[int], *, m: int, k: int, s: int) -> float:
    return log(exact_r_exponent(a, sequence, m=m, k=k, s=s), s)


# ---------------------------------------------------------------------------
# Centered internal-state representation and frequency profiles
# ---------------------------------------------------------------------------

def eta(sigma: int, s: int) -> Fraction:
    assert 1 <= sigma <= s
    return Fraction(2 * sigma - s - 1, 2)


def B_s(s: int) -> Fraction:
    assert s >= 2
    return Fraction(s - 1, 2)


def counts_by_state(sequence: Sequence[int], s: int) -> dict[int, int]:
    assert all(1 <= sigma <= s for sigma in sequence)
    return {sigma: sum(1 for z in sequence if z == sigma) for sigma in range(1, s + 1)}


def frequencies_by_state(sequence: Sequence[int], s: int) -> dict[int, Fraction]:
    n = len(sequence)
    assert n >= 1
    counts = counts_by_state(sequence, s)
    return {sigma: Fraction(counts[sigma], n) for sigma in range(1, s + 1)}


def cumulative_spin(sequence: Sequence[int], s: int) -> Fraction:
    assert all(1 <= sigma <= s for sigma in sequence)
    return sum((eta(sigma, s) for sigma in sequence), Fraction(0))


def normalized_spin(sequence: Sequence[int], s: int) -> Fraction:
    n = len(sequence)
    assert n >= 1
    return cumulative_spin(sequence, s) / n


def frequency_profile_spin(sequence: Sequence[int], s: int) -> Fraction:
    freqs = frequencies_by_state(sequence, s)
    return sum((eta(sigma, s) * freqs[sigma] for sigma in range(1, s + 1)), Fraction(0))


