"""
VERIFICATION of Section: Recursive macro-classes of causal microhistories
(sec:recursive-macro-classes).

This is a full mathematical verification block for
1_recursive_macro_classes.tex.

Scope
-----
This script verifies the new mathematical layer introduced in the file:
recursive compatibility of finite prefixes, macro-equivalence, finite
projections of macro-classes, frequency profiles of the normalized cumulative
spin coordinate barSigma_n, one-step recursive refinement, and branching under unlimited
continuation.

It intentionally does not re-prove the global bijectivity of F, the level
construction, the exact digit coordinate theorem, or the normalized-coordinate
spectrum theorem.  Those results are used only through their previously
verified formulas:

    D = sum_j (sigma_j - 1) s^{n-j},
    Delta rho = D / s^n,
    r_n = log_s(u_n + 1),
    eta(sigma) = sigma - (s+1)/2.

Verification safeguards
-----------------------------------------
1. Expected-failure tests are now sound.  The manual failure is raised outside
   the exception handler, so an invalid case is accepted only if the tested
   function itself rejects it.

2. The O(1) clause for the logarithmic coordinate is not replaced by equality
   of leading slopes.  Macro-equivalence stores an explicit O(1)-class label,
   and a separate symbolic block proves that equal leading slopes are not
   sufficient: examples with log(n) and sqrt(n) have the same slope but
   unbounded difference.

3. Branching is split into two checks:
   - actual pure continuations from a finite prefix are verified to land in
     different macro-classes;
   - a separate profile-level witness isolates the spin clause by keeping the
     rho-limit and O(1)-class fixed while changing only the spin limit.

4. Finite projections are checked with strict realization requirements.  The
   script also verifies that a proposed non-singleton projection generated by
   the usual ambiguous base-s expansions is not a valid macro-class projection
   under the full definition, because the spin-limit clause rejects it.  This
   prevents a false positive non-singleton test.

5. The centered spectrum is verified symbolically for arbitrary s >= 2:
   zero total sum, unit spacing, endpoint extrema, and B_s=(s-1)/2.

Terminology
-----------
Finite internal-state data are called prefixes or state sequences.  The script
avoids treating spin data as linguistic objects.

Expected result
---------------
All assertions pass and the final line reports successful completion.
"""

