@dataclass(frozen=True)
class FiniteMacroClass:
    representatives: tuple[EventuallyPeriodicFamily, ...]
    s: int
    a: int
    r_O1_class: str = "generated-O1-class"

    def __post_init__(self) -> None:
        assert len(self.representatives) >= 1
        profiles = []
        for rep in self.representatives:
            assert rep.s == self.s
            assert rep.a == self.a
            profiles.append(profile_from_family(rep, r_O1_class=self.r_O1_class))
        base = profiles[0]
        for profile in profiles[1:]:
            assert macro_equivalent_profiles(base, profile)

    def projection(self, n: int) -> set[tuple[int, StateSequence]]:
        assert n >= 1
        return {(self.a, rep.prefix(n)) for rep in self.representatives}


