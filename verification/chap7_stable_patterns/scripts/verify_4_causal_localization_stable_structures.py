def verify_emergent_boundary_as_loss_of_recursive_compatibility() -> None:
    print("\n=== Boundary as loss of recursive compatibility/admissibility ===")

    def admissible(prefix: StatePrefix, center: Fraction, radius: Fraction, max_digit: int) -> bool:
        return abs(prefix.delta_rho - center) <= radius and prefix.digit_coordinate <= max_digit

    center = Fraction(0)
    radius = Fraction(1, 8)
    max_digit = 3

    level_3 = all_prefixes(2, 3)
    admissible_level_3 = tuple(p for p in level_3 if admissible(p, center, radius, max_digit))
    rejected_level_3 = tuple(p for p in level_3 if not admissible(p, center, radius, max_digit))

    assert admissible_level_3
    assert rejected_level_3
    assert set(admissible_level_3).isdisjoint(rejected_level_3)
    assert len(admissible_level_3) + len(rejected_level_3) == len(level_3)

    next_candidates = all_prefixes(2, 4)
    compatible_next = tuple(
        p for p in next_candidates if p.parent() in set(admissible_level_3) and admissible(p, center, radius, max_digit)
    )
    boundary_failures = tuple(
        p
        for p in next_candidates
        if p.parent() in set(admissible_level_3) and not admissible(p, center, radius, max_digit)
    )

    assert compatible_next
    assert boundary_failures
    for p in boundary_failures:
        assert p.parent() in set(admissible_level_3)
        assert not admissible(p, center, radius, max_digit)

    # The boundary changes when the organization predicate changes, so it is not
    # a fixed external cut imposed independently of the recursive structure.
    larger_radius = Fraction(1, 4)
    enlarged_admissible = tuple(p for p in level_3 if admissible(p, center, larger_radius, max_digit))
    assert set(admissible_level_3).issubset(set(enlarged_admissible))
    assert len(enlarged_admissible) > len(admissible_level_3)

    print("[OK] Accepted region is exactly the recursively compatible admissible region")
    print("[OK] Boundary failures are compatible refinements that leave the controlled geometric profile")
    print("[OK] Changing the organization predicate changes the boundary, so no fixed external cut is used")


def verify_geometric_localization_does_not_fix_internal_organization() -> None:
    print("\n=== Geometric localization versus internal-state organization ===")

    organized = InternalOrganization(
        name="geometrically localized and internally convergent",
        geometric_data=STRONG_GEOMETRY,
        internal_frequency_limit=Fraction(1, 2),
        internal_frequency_convergent=True,
    )
    blurred_limit = InternalOrganization(
        name="same geometry but different internal limit",
        geometric_data=STRONG_GEOMETRY,
        internal_frequency_limit=Fraction(1, 3),
        internal_frequency_convergent=True,
    )
    nonconvergent_internal = InternalOrganization(
        name="same geometry but nonconvergent internal frequencies",
        geometric_data=STRONG_GEOMETRY,
        internal_frequency_limit=None,
        internal_frequency_convergent=False,
    )

    assert organized.passes_geometric_localization()
    assert blurred_limit.passes_geometric_localization()
    assert nonconvergent_internal.passes_geometric_localization()

    assert organized.passes_internal_organization()
    assert blurred_limit.passes_internal_organization()
    assert organized.internal_frequency_limit != blurred_limit.internal_frequency_limit
    assert not nonconvergent_internal.passes_internal_organization()

    print("[OK] Identical geometric localization data can coexist with different internal-state frequency data")
    print("[OK] Geometric localization alone does not enforce internal-state organization")
    print("[OK] Nonconvergent internal organization is invisible to the geometric localization predicate")


def verify_exact_examples_of_rho_spread_inside_causal_cone() -> None:
    print("\n=== Exact examples of causal-cone spread and localization regimes ===")

    # Strong finite family: two prefixes whose normalized spread tends to zero
    # while logarithmic spread remains bounded.
    for n in range(4, 18):
        left = StatePrefix(tuple([1] * n), 2)
        near_left = StatePrefix(tuple([1] * (n - 2) + [2, 2]), 2)
        projection = (left, near_left)
        rho_spread = delta_rho_diameter(projection)
        r_spread = r_diameter_expr(projection)
        assert rho_spread == Fraction(3, 2**n)
        assert simplify(r_spread - log(4) / log(2)) == 0

    # Full-cone finite family: the leftmost and rightmost prefixes fill almost
    # the whole normalized coordinate range, and logarithmic spread grows.
    for n in range(2, 12):
        left = StatePrefix(tuple([1] * n), 2)
        right = StatePrefix(tuple([2] * n), 2)
        projection = (left, right)
        rho_spread = delta_rho_diameter(projection)
        assert rho_spread == Fraction(2**n - 1, 2**n)
        assert simplify(r_diameter_expr(projection) - n) == 0

    print("[OK] Strong finite witnesses have D_rho -> 0 and bounded D_r")
    print("[OK] Full-cone finite witnesses have D_rho -> 1 and unbounded D_r")


