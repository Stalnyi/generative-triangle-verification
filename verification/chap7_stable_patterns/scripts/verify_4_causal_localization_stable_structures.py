def verify_finite_geometric_profiles_and_diameters() -> None:
    print("\n=== Finite geometric profiles and exact diameters ===")

    checked = 0
    for s in (2, 3, 4):
        for n in range(1, 6):
            universe = all_prefixes(s, n)
            # Several deterministic nontrivial projections, including singleton,
            # sparse subsets, and the full finite causal layer.
            projections = [
                universe[:1],
                universe[:: max(1, len(universe) // min(len(universe), 7))],
                universe[-min(len(universe), 5) :],
                universe,
            ]
            for projection in projections:
                projection = finite_projection(projection)
                rho_values = delta_rho_profile(projection)
                direct_rho_values = {p.delta_rho for p in projection}
                assert rho_values == direct_rho_values

                rho_diam = delta_rho_diameter(projection)
                assert rho_diam == max(rho_values) - min(rho_values)
                assert rho_diam == max(abs(a - b) for a in rho_values for b in rho_values)
                assert Fraction(0) <= rho_diam < Fraction(1)

                r_values = r_profile(projection)
                assert len(r_values) == len({p.digit_coordinate for p in projection})

                d_min = min(p.digit_coordinate for p in projection)
                d_max = max(p.digit_coordinate for p in projection)
                expected_r_diam = log(Rational(d_max + 1, d_min + 1)) / log(s)
                assert simplify(r_diameter_expr(projection) - expected_r_diam) == 0
                assert simplify(r_diameter_expr(projection)) >= 0
                checked += 1

    expect_raises(ValueError, lambda: finite_projection(()), "empty finite projection")
    expect_raises(ValueError, lambda: StatePrefix((), 2), "empty geometric prefix")
    expect_raises(ValueError, lambda: StatePrefix((1, 3), 2), "state outside S")
    expect_raises(ValueError, lambda: finite_projection((StatePrefix((1,), 2), StatePrefix((1,), 3))), "mixed bases")
    expect_raises(ValueError, lambda: finite_projection((StatePrefix((1,), 2), StatePrefix((1, 1), 2))), "mixed levels")

    print(f"[OK] Checked {checked} finite projections over several bases and levels")
    print("[OK] Delta-rho and logarithmic profiles are exact images of finite projections")
    print("[OK] D_rho and D_r are exact finite pairwise suprema")
    print("[OK] Invalid finite projections and invalid internal-state prefixes are rejected soundly")


def verify_symbolic_logarithmic_diameter_formula() -> None:
    print("\n=== Symbolic verification of logarithmic diameter formula ===")

    s = Symbol("s", integer=True, positive=True)
    d_min = Symbol("d_min", integer=True, nonnegative=True)
    d_max = Symbol("d_max", integer=True, nonnegative=True)

    r_min = log(d_min + 1) / log(s)
    r_max = log(d_max + 1) / log(s)
    diameter = r_max - r_min
    expected = log((d_max + 1) / (d_min + 1)) / log(s)

    assert simplify(diameter - expected) == 0

    # Concrete exact substitutions avoid relying on an ordering engine for log.
    for base in range(2, 8):
        for a in range(0, 12):
            for b in range(a, 18):
                value = expected.subs({s: base, d_min: a, d_max: b})
                assert float(value) >= -1e-12
                if a == b:
                    assert simplify(value) == 0
                else:
                    assert float(value) > 0

    print("[OK] D_r = log_s((D_max+1)/(D_min+1)) follows symbolically from r=log_s(D+1)")
    print("[OK] Boundary and positivity cases were checked for exact integer coordinates")


def verify_weak_and_strong_localization_logic() -> None:
    print("\n=== Weak and strong causal-localization logic ===")

    assert STRONG_GEOMETRY.strongly_localized()
    assert STRONG_GEOMETRY.weakly_localized()

