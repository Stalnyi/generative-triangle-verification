@dataclass(frozen=True)
class AsymptoticGeometry:
    name: str
    rho_diameter: Callable[[int], Fraction]
    r_diameter_expr: Callable[[Symbol], object]
    rho_limsup: Fraction
    rho_limit: Fraction | None
    r_is_O1: bool

    def weakly_localized(self) -> bool:
        return self.rho_limsup < 1 or self.r_is_O1

    def strongly_localized(self) -> bool:
        return self.rho_limit == 0 and self.r_is_O1

    def not_localized(self) -> bool:
        # Since D_{rho,n} is a diameter inside [0,1), the only possible failure
        # of limsup < 1 is limsup = 1.
        return self.rho_limsup == 1 and not self.r_is_O1

    def shifted(self, k: int) -> "AsymptoticGeometry":
        if k < 0:
            raise ValueError("Tail shift must be nonnegative")

        def shifted_rho(n: int) -> Fraction:
            return self.rho_diameter(n + k)

        return AsymptoticGeometry(
            name=f"{self.name}[tail+{k}]",
            rho_diameter=shifted_rho,
            r_diameter_expr=lambda n, self=self, k=k: self.r_diameter_expr(n + k),
            rho_limsup=self.rho_limsup,
            rho_limit=self.rho_limit,
            r_is_O1=self.r_is_O1,
        )


