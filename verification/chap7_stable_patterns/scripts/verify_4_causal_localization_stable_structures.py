def expect_raises(expected_exception: type[BaseException], thunk: Callable[[], object], label: str) -> None:
    """Fail unless thunk raises expected_exception directly."""
    try:
        thunk()
    except expected_exception:
        return
    raise AssertionError(f"Expected {expected_exception.__name__} was not raised: {label}")


@dataclass(frozen=True)
class StatePrefix:
    """Finite internal-state prefix over S={1,...,s}."""

    states: tuple[int, ...]
    s: int

    def __post_init__(self) -> None:
        if self.s < 2:
            raise ValueError("The base s must satisfy s >= 2")
        if len(self.states) == 0:
            raise ValueError("A finite prefix used for geometric coordinates must be nonempty")
        if any(state < 1 or state > self.s for state in self.states):
            raise ValueError("Every internal state must lie in {1,...,s}")

    @property
    def level(self) -> int:
        return len(self.states)

    @property
    def digit_coordinate(self) -> int:
        # The zero-based digit is state-1.  The first state is the most
        # significant digit of the causal-layer coordinate.
        total = 0
        n = self.level
        for index, state in enumerate(self.states):
            total += (state - 1) * self.s ** (n - index - 1)
        return total

    @property
    def delta_rho(self) -> Fraction:
        return Fraction(self.digit_coordinate, self.s ** self.level)

    @property
    def r_expr(self):
        return log(self.digit_coordinate + 1) / log(self.s)

    def parent(self) -> "StatePrefix | None":
        if self.level == 1:
            return None
        return StatePrefix(self.states[:-1], self.s)

    def extends_by_one(self, previous: "StatePrefix") -> bool:
        return self.s == previous.s and self.level == previous.level + 1 and self.states[:-1] == previous.states


def finite_projection(prefixes: Iterable[StatePrefix]) -> tuple[StatePrefix, ...]:
    projection = tuple(prefixes)
    if not projection:
        raise ValueError("Finite projection must be nonempty")
    base = projection[0].s
    level = projection[0].level
    if any(p.s != base for p in projection):
        raise ValueError("All prefixes in one projection must use the same base s")
    if any(p.level != level for p in projection):
        raise ValueError("All prefixes in one projection must belong to the same level")
    # remove duplicates while preserving deterministic order
    seen: set[tuple[int, ...]] = set()
    unique: list[StatePrefix] = []
    for p in projection:
        if p.states not in seen:
            seen.add(p.states)
            unique.append(p)
    return tuple(unique)


def delta_rho_profile(projection: Sequence[StatePrefix]) -> set[Fraction]:
    return {p.delta_rho for p in finite_projection(projection)}


def r_profile(projection: Sequence[StatePrefix]):
    return {p.r_expr for p in finite_projection(projection)}


def pairwise_fraction_diameter(values: Iterable[Fraction]) -> Fraction:
    vals = tuple(values)
    if not vals:
        raise ValueError("Diameter of an empty set is undefined")
    return max(abs(a - b) for a in vals for b in vals)


def delta_rho_diameter(projection: Sequence[StatePrefix]) -> Fraction:
    values = delta_rho_profile(projection)
    return pairwise_fraction_diameter(values)


def r_diameter_expr(projection: Sequence[StatePrefix]):
    proj = finite_projection(projection)
    digits = [p.digit_coordinate for p in proj]
    s = proj[0].s
    d_min = min(digits)
    d_max = max(digits)
    return log(Rational(d_max + 1, d_min + 1)) / log(s)


def all_prefixes(s: int, n: int) -> tuple[StatePrefix, ...]:
    return tuple(StatePrefix(tuple(states), s) for states in product(range(1, s + 1), repeat=n))


