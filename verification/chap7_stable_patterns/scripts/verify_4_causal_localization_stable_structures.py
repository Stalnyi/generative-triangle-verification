@dataclass(frozen=True)
class RefinementTower:
    name: str
    projections: tuple[tuple[StatePrefix, ...], ...]
    geometry: AsymptoticGeometry

    def __post_init__(self) -> None:
        if not self.projections:
            raise ValueError("A refinement tower must contain at least one projection")
        for projection in self.projections:
            finite_projection(projection)

    def is_recursively_compatible(self) -> bool:
        for previous, current in zip(self.projections, self.projections[1:]):
            previous_set = set(previous)
            for prefix in current:
                parent = prefix.parent()
                if parent not in previous_set:
                    return False
        return True

    def tail_geometry(self, k: int) -> AsymptoticGeometry:
        return self.geometry.shifted(k)


def contained_in_mode(towers: Sequence[RefinementTower], mode: str, max_tail_shift_checked: int = 8) -> bool:
    if mode not in {"weak", "strong"}:
        raise ValueError("mode must be 'weak' or 'strong'")
    if not towers:
        raise ValueError("Causal containment cannot be verified from an empty family of continuations")
    for tower in towers:
        if not tower.is_recursively_compatible():
            return False
        for k in range(max_tail_shift_checked + 1):
            tail = tower.tail_geometry(k)
            if mode == "weak" and not tail.weakly_localized():
                return False
            if mode == "strong" and not tail.strongly_localized():
                return False
    return True


def make_refinement_tower(base: int = 2, height: int = 5, branch_state: int = 1, geometry: AsymptoticGeometry = STRONG_GEOMETRY) -> RefinementTower:
    projections: list[tuple[StatePrefix, ...]] = []
    for n in range(1, height + 1):
        prefix = StatePrefix(tuple([branch_state] * n), base)
        projections.append((prefix,))
    return RefinementTower("single compatible refinement tower", tuple(projections), geometry)


def make_incompatible_tower() -> RefinementTower:
    return RefinementTower(
        "incompatible branch jump",
        (
            (StatePrefix((1,), 2),),
            (StatePrefix((2, 1), 2),),  # parent is (2,), not the previous prefix (1,)
        ),
        STRONG_GEOMETRY,
    )


