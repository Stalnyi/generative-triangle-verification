    assert not WEAK_BY_RHO_ONLY.strongly_localized()

    assert WEAK_BY_R_ONLY.weakly_localized()
    assert not WEAK_BY_R_ONLY.strongly_localized()

    assert not NONLOCAL_LOG.weakly_localized()
    assert not NONLOCAL_LOG.strongly_localized()
