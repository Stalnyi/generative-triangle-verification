@dataclass(frozen=True)
class CandidateStructure:
    name: str
    recursively_stable: bool
    geometry: AsymptoticGeometry
    contained: bool

    def localized_recursively_stable(self, mode: str = "weak") -> bool:
        if mode == "weak":
            localized = self.geometry.weakly_localized()
        elif mode == "strong":
            localized = self.geometry.strongly_localized()
        else:
            raise ValueError("mode must be 'weak' or 'strong'")
        return self.recursively_stable and localized and self.contained


@dataclass(frozen=True)
class InternalOrganization:
    name: str
    geometric_data: AsymptoticGeometry
    internal_frequency_limit: Fraction | None
    internal_frequency_convergent: bool

    def passes_geometric_localization(self) -> bool:
        return self.geometric_data.weakly_localized()

    def passes_internal_organization(self) -> bool:
        return self.internal_frequency_convergent and self.internal_frequency_limit is not None


